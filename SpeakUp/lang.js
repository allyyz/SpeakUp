const getLang = () => localStorage.getItem('lang') || 'en';
let langObs;
function trText(s) {
  const k = s.trim();
  if (!k) return s;
  let v = TL[k];
  if (!v) for (const [re, fn] of TP) { const m = k.match(re); if (m) { v = fn(m); break; } }
  return v ? s.replace(k, () => v) : s;
}
function translatePage() {
  if (getLang() !== 'tl' || !document.body) return;
  if (langObs) langObs.disconnect();
  const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = w.nextNode())) {
    const p = node.parentNode;
    if (!p || p.tagName === 'SCRIPT' || p.tagName === 'STYLE') continue;
    const n = trText(node.nodeValue);
    if (n !== node.nodeValue) {
      if (p.tagName === 'OPTION' && !p.hasAttribute('value')) p.setAttribute('value', node.nodeValue.trim());
      node.nodeValue = n;
    }
  }
  document.querySelectorAll('[placeholder]').forEach(el => {
    const o = el.dataset.ph || el.getAttribute('placeholder');
    el.dataset.ph = o;
    const t = { 'What happened? When and where? Who was involved?': 'Ano ang nangyari? Kailan at saan? Sino ang kasama?' }[o];
    if (t) el.setAttribute('placeholder', t);
  });
  if (langObs) langObs.observe(document.body, { childList: true, subtree: true });
}
function initLang() {
  if (!document.body || document.getElementById('langBtn')) return;
  const b = document.createElement('button');
  b.id = 'langBtn';
  b.textContent = getLang() === 'tl' ? 'EN | TL ✓' : 'EN ✓ | TL';
  b.style.cssText = 'position:fixed;right:14px;bottom:14px;z-index:99;padding:.6rem 1rem;border:0;border-radius:999px;background:#14325c;color:#fff;font-size:.95rem;box-shadow:0 4px 14px rgba(0,0,0,.25)';
  b.onclick = () => { localStorage.setItem('lang', getLang() === 'tl' ? 'en' : 'tl'); location.reload(); };
  document.body.appendChild(b);
  langObs = new MutationObserver(translatePage);
  translatePage();
}
document.addEventListener('DOMContentLoaded', initLang);
